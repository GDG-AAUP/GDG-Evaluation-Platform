BEGIN;

SET LOCAL lock_timeout = '5s';

SET LOCAL statement_timeout = '60s';

DO $$
BEGIN
  IF EXISTS(SELECT 1 FROM information_schema.columns WHERE table_schema=current_schema() AND table_name='users' AND column_name='password_hash') THEN
    IF EXISTS(SELECT 1 FROM users WHERE password_hash IS NOT NULL OR external_auth_id IS NOT NULL) THEN
      RAISE EXCEPTION 'Legacy authentication data must be archived before removing its columns';
    END IF;
  END IF;
END
$$;

ALTER TABLE users ALTER COLUMN email TYPE VARCHAR(255);

ALTER TABLE users ALTER COLUMN clerk_user_id DROP NOT NULL;

ALTER TABLE users DROP COLUMN IF EXISTS password_hash;

ALTER TABLE users DROP COLUMN IF EXISTS external_auth_id;

ALTER TABLE campuses ALTER COLUMN created_at SET NOT NULL;

ALTER TABLE teams ALTER COLUMN created_at SET NOT NULL;

ALTER TABLE teams ALTER COLUMN is_operational SET DEFAULT FALSE;

ALTER TABLE assignment_history ALTER COLUMN assignment_id TYPE BIGINT;

ALTER TABLE point_entries ALTER COLUMN entry_id TYPE BIGINT, ALTER COLUMN reverses_entry_id TYPE BIGINT;

ALTER TABLE monthly_rankings ALTER COLUMN ranking_id TYPE BIGINT, ALTER COLUMN month TYPE SMALLINT, ALTER COLUMN year TYPE SMALLINT;

ALTER TABLE audit_logs ALTER COLUMN audit_id TYPE BIGINT, ALTER COLUMN old_values TYPE JSONB USING old_values::jsonb, ALTER COLUMN new_values TYPE JSONB USING new_values::jsonb;

DO $$
BEGIN
  IF to_regclass('manager_evaluations') IS NOT NULL THEN
    CREATE SCHEMA IF NOT EXISTS gdg_legacy;
    IF to_regclass('gdg_legacy.manager_evaluations') IS NOT NULL THEN
      RAISE EXCEPTION 'Legacy evaluation archive already exists; reconcile before migrating';
    END IF;
    ALTER TABLE manager_evaluations SET SCHEMA gdg_legacy;
  END IF;
END
$$;

CREATE TABLE IF NOT EXISTS performance_evaluations (
 evaluation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 evaluated_user_id INT NOT NULL,
 evaluated_by_user_id INT NOT NULL,
 team_id INT NOT NULL,
 campus_id INT NOT NULL,
 activity_name VARCHAR(150) NOT NULL,
 activity_date TIMESTAMP WITHOUT TIME ZONE NOT NULL,
 criteria_scores JSONB NOT NULL,
 criteria_total_score SMALLINT NOT NULL,
 criteria_max_score SMALLINT NOT NULL DEFAULT 100,
 comments TEXT NULL,
 created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_perf_target FOREIGN KEY (evaluated_user_id) REFERENCES users(user_id),
 CONSTRAINT fk_perf_actor FOREIGN KEY (evaluated_by_user_id) REFERENCES users(user_id),
 CONSTRAINT fk_perf_team FOREIGN KEY (team_id) REFERENCES teams(team_id),
 CONSTRAINT fk_perf_campus FOREIGN KEY (campus_id) REFERENCES campuses(campus_id),
 CONSTRAINT chk_perf_scores CHECK (criteria_max_score = 100 AND criteria_total_score BETWEEN 0 AND 100),
 CONSTRAINT chk_perf_criteria_count CHECK (jsonb_typeof(criteria_scores) = 'array' AND jsonb_array_length(criteria_scores) = 15),
 CONSTRAINT chk_perf_activity CHECK (CHAR_LENGTH(TRIM(activity_name)) > 0),
 CONSTRAINT chk_perf_not_self CHECK (evaluated_user_id <> evaluated_by_user_id)
);

DO $$
BEGIN
  IF NOT EXISTS(SELECT 1 FROM pg_constraint WHERE conrelid='campuses'::regclass AND conname='chk_campus_name') THEN
    ALTER TABLE campuses ADD CONSTRAINT chk_campus_name CHECK (CHAR_LENGTH(TRIM(campus_name)) > 0);
  END IF;
END
$$;

DO $$
BEGIN
  IF NOT EXISTS(SELECT 1 FROM pg_constraint WHERE conrelid='users'::regclass AND conname='chk_user_name') THEN
    ALTER TABLE users ADD CONSTRAINT chk_user_name CHECK (CHAR_LENGTH(TRIM(full_name)) > 0);
  END IF;
END
$$;

DO $$
BEGIN
  IF NOT EXISTS(SELECT 1 FROM pg_constraint WHERE conrelid='users'::regclass AND conname='chk_user_role_team') THEN
    ALTER TABLE users ADD CONSTRAINT chk_user_role_team CHECK ((role='Organizer' AND team_id IS NULL) OR (role IN ('Manager','Member') AND team_id IS NOT NULL));
  END IF;
END
$$;

DO $$
BEGIN
  IF NOT EXISTS(SELECT 1 FROM pg_constraint WHERE conrelid='users'::regclass AND conname='chk_user_clerk_invitation') THEN
    ALTER TABLE users ADD CONSTRAINT chk_user_clerk_invitation CHECK (clerk_user_id IS NOT NULL OR invitation_status IN ('pending','sending','sent','failed'));
  END IF;
END
$$;

DO $$
BEGIN
  IF NOT EXISTS(SELECT 1 FROM pg_constraint WHERE conrelid='teams'::regclass AND conname='uq_team_name_per_campus') THEN
    ALTER TABLE teams ADD CONSTRAINT uq_team_name_per_campus UNIQUE (campus_id,team_name);
  END IF;
END
$$;

DO $$
BEGIN
  IF NOT EXISTS(SELECT 1 FROM pg_constraint WHERE conrelid='teams'::regclass AND conname='chk_team_name') THEN
    ALTER TABLE teams ADD CONSTRAINT chk_team_name CHECK (CHAR_LENGTH(TRIM(team_name)) > 0);
  END IF;
END
$$;

DO $$
BEGIN
  IF NOT EXISTS(SELECT 1 FROM pg_constraint WHERE conrelid='teams'::regclass AND conname='chk_operational_manager') THEN
    ALTER TABLE teams ADD CONSTRAINT chk_operational_manager CHECK (is_operational=FALSE OR manager_user_id IS NOT NULL);
  END IF;
END
$$;

DO $$
BEGIN
  IF NOT EXISTS(SELECT 1 FROM pg_constraint WHERE conrelid='point_entries'::regclass AND conname='chk_points_text') THEN
    ALTER TABLE point_entries ADD CONSTRAINT chk_points_text CHECK (CHAR_LENGTH(TRIM(activity_name)) > 0 AND CHAR_LENGTH(TRIM(reason)) > 0);
  END IF;
END
$$;

DO $$
BEGIN
  IF NOT EXISTS(SELECT 1 FROM pg_constraint WHERE conrelid='point_entries'::regclass AND conname='chk_points_not_self_reverse') THEN
    ALTER TABLE point_entries ADD CONSTRAINT chk_points_not_self_reverse CHECK (reverses_entry_id IS NULL OR reverses_entry_id <> entry_id);
  END IF;
END
$$;

DO $$
BEGIN
  IF NOT EXISTS(SELECT 1 FROM pg_constraint WHERE conrelid='monthly_rankings'::regclass AND conname='uq_user_month_scope') THEN
    ALTER TABLE monthly_rankings ADD CONSTRAINT uq_user_month_scope UNIQUE (user_id,ranking_scope,month,year);
  END IF;
END
$$;

CREATE INDEX IF NOT EXISTS idx_history_user_period ON assignment_history (user_id,effective_from,effective_to);

CREATE INDEX IF NOT EXISTS idx_points_user_effective ON point_entries (user_id,effective_at);

CREATE INDEX IF NOT EXISTS idx_rank_lookup ON monthly_rankings (ranking_scope,campus_id,team_id,year,month,rank_position);

CREATE INDEX IF NOT EXISTS idx_perf_target_date ON performance_evaluations (evaluated_user_id,activity_date);

CREATE INDEX IF NOT EXISTS idx_perf_team_date ON performance_evaluations (team_id,activity_date);

CREATE INDEX IF NOT EXISTS idx_audit_entity ON audit_logs (entity_name,entity_id);

CREATE INDEX IF NOT EXISTS idx_audit_date ON audit_logs (created_at);

COMMIT;
