CREATE INDEX idx_history_user_period ON assignment_history (user_id,effective_from,effective_to);
CREATE INDEX idx_points_user_effective ON point_entries (user_id,effective_at);
CREATE INDEX idx_rank_lookup ON monthly_rankings (ranking_scope,campus_id,team_id,year,month,rank_position);
CREATE INDEX idx_perf_target_date ON performance_evaluations (evaluated_user_id,activity_date);
CREATE INDEX idx_perf_team_date ON performance_evaluations (team_id,activity_date);
CREATE INDEX idx_audit_entity ON audit_logs (entity_name,entity_id);
CREATE INDEX idx_audit_date ON audit_logs (created_at);

COMMIT;
