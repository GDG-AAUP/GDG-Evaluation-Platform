BEGIN;

CREATE TABLE campuses (
 campus_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 campus_name VARCHAR(100) NOT NULL UNIQUE,
 created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT chk_campus_name CHECK (CHAR_LENGTH(TRIM(campus_name)) > 0)
);

CREATE TABLE users (
 user_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 clerk_user_id VARCHAR(255) NULL UNIQUE,
 full_name VARCHAR(100) NOT NULL,
 email VARCHAR(255) NOT NULL UNIQUE,
 role VARCHAR(20) CHECK (role IN ('Organizer','Manager','Member')) NOT NULL,
 team_id INT NULL,
 is_active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT chk_user_name CHECK (CHAR_LENGTH(TRIM(full_name)) > 0),
 CONSTRAINT chk_user_role_team CHECK ((role='Organizer' AND team_id IS NULL) OR (role IN ('Manager','Member') AND team_id IS NOT NULL))
);

CREATE TABLE teams (
 team_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 campus_id INT NOT NULL,
 team_name VARCHAR(100) NOT NULL,
 manager_user_id INT NULL UNIQUE,
 is_operational BOOLEAN NOT NULL DEFAULT FALSE,
 description TEXT NULL,
 created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_team_campus FOREIGN KEY (campus_id) REFERENCES campuses(campus_id),
 CONSTRAINT fk_team_manager FOREIGN KEY (manager_user_id) REFERENCES users(user_id),
 CONSTRAINT uq_team_name_per_campus UNIQUE (campus_id,team_name),
 CONSTRAINT chk_team_name CHECK (CHAR_LENGTH(TRIM(team_name)) > 0),
 CONSTRAINT chk_operational_manager CHECK (is_operational=FALSE OR manager_user_id IS NOT NULL)
);
ALTER TABLE users ADD CONSTRAINT fk_user_team FOREIGN KEY (team_id) REFERENCES teams(team_id);

CREATE TABLE assignment_history (
 assignment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id INT NOT NULL,
 team_id INT NOT NULL,
 role_at_time VARCHAR(20) CHECK (role_at_time IN ('Manager','Member')) NOT NULL,
 effective_from TIMESTAMP WITHOUT TIME ZONE NOT NULL,
 effective_to TIMESTAMP WITHOUT TIME ZONE NULL,
 changed_by_user_id INT NULL,
 reason TEXT NULL,
 CONSTRAINT fk_hist_user FOREIGN KEY (user_id) REFERENCES users(user_id),
 CONSTRAINT fk_hist_team FOREIGN KEY (team_id) REFERENCES teams(team_id),
 CONSTRAINT fk_hist_actor FOREIGN KEY (changed_by_user_id) REFERENCES users(user_id),
 CONSTRAINT chk_history_dates CHECK (effective_to IS NULL OR effective_to > effective_from)
);

CREATE TABLE point_entries (
 entry_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id INT NOT NULL,
 performed_by_user_id INT NOT NULL,
 points INT NOT NULL,
 activity_name VARCHAR(100) NOT NULL,
 reason TEXT NOT NULL,
 activity_description TEXT NULL,
 created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 effective_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 reverses_entry_id BIGINT NULL UNIQUE,
 CONSTRAINT fk_points_user FOREIGN KEY (user_id) REFERENCES users(user_id),
 CONSTRAINT fk_points_actor FOREIGN KEY (performed_by_user_id) REFERENCES users(user_id),
 CONSTRAINT fk_points_reverse FOREIGN KEY (reverses_entry_id) REFERENCES point_entries(entry_id),
 CONSTRAINT chk_points_range CHECK (points BETWEEN -100 AND 100 AND points <> 0),
 CONSTRAINT chk_points_text CHECK (CHAR_LENGTH(TRIM(activity_name)) > 0 AND CHAR_LENGTH(TRIM(reason)) > 0),
 CONSTRAINT chk_points_not_self_reverse CHECK (reverses_entry_id IS NULL OR reverses_entry_id <> entry_id)
);

CREATE TABLE monthly_rankings (
 ranking_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id INT NOT NULL,
 ranking_scope VARCHAR(20) CHECK (ranking_scope IN ('Team','Campus')) NOT NULL,
 team_id INT NULL,
 campus_id INT NOT NULL,
 month SMALLINT NOT NULL,
 year SMALLINT NOT NULL,
 total_points INT NOT NULL DEFAULT 0,
 rank_position INT NOT NULL,
 archived_at TIMESTAMP WITHOUT TIME ZONE NULL,
 last_revised_at TIMESTAMP WITHOUT TIME ZONE NULL,
 CONSTRAINT fk_rank_user FOREIGN KEY (user_id) REFERENCES users(user_id),
 CONSTRAINT fk_rank_team FOREIGN KEY (team_id) REFERENCES teams(team_id),
 CONSTRAINT fk_rank_campus FOREIGN KEY (campus_id) REFERENCES campuses(campus_id),
 CONSTRAINT uq_user_month_scope UNIQUE (user_id,ranking_scope,month,year),
 CONSTRAINT chk_rank_month CHECK (month BETWEEN 1 AND 12),
 CONSTRAINT chk_rank_year CHECK (year >= 2000),
 CONSTRAINT chk_rank_position CHECK (rank_position >= 1),
 CONSTRAINT chk_rank_scope CHECK ((ranking_scope='Team' AND team_id IS NOT NULL) OR (ranking_scope='Campus' AND team_id IS NULL))
);

CREATE TABLE performance_evaluations (
 evaluation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 evaluated_user_id INT NOT NULL,
 evaluated_by_user_id INT NOT NULL,
 team_id INT NOT NULL,
 campus_id INT NOT NULL,
 activity_name VARCHAR(150) NOT NULL,
 activity_date TIMESTAMP WITHOUT TIME ZONE NOT NULL,
 criteria_scores JSONB NOT NULL,
 criteria_total_score SMALLINT NOT NULL,
 criteria_max_score SMALLINT NOT NULL DEFAULT 100,
 comments TEXT NULL,
 created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_perf_target FOREIGN KEY (evaluated_user_id) REFERENCES users(user_id),
 CONSTRAINT fk_perf_actor FOREIGN KEY (evaluated_by_user_id) REFERENCES users(user_id),
 CONSTRAINT fk_perf_team FOREIGN KEY (team_id) REFERENCES teams(team_id),
 CONSTRAINT fk_perf_campus FOREIGN KEY (campus_id) REFERENCES campuses(campus_id),
 CONSTRAINT chk_perf_scores CHECK (criteria_max_score = 100 AND criteria_total_score BETWEEN 0 AND 100),
 CONSTRAINT chk_perf_criteria_count CHECK (jsonb_typeof(criteria_scores) = 'array' AND jsonb_array_length(criteria_scores) = 15),
 CONSTRAINT chk_perf_activity CHECK (CHAR_LENGTH(TRIM(activity_name)) > 0),
 CONSTRAINT chk_perf_not_self CHECK (evaluated_user_id <> evaluated_by_user_id)
);

CREATE TABLE audit_logs (
 audit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 actor_user_id INT NULL,
 action VARCHAR(100) NOT NULL,
 entity_name VARCHAR(100) NOT NULL,
 entity_id VARCHAR(100) NULL,
 old_values JSONB NULL,
 new_values JSONB NULL,
 reason TEXT NULL,
 batch_id CHAR(36) NULL,
 created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_audit_actor FOREIGN KEY (actor_user_id) REFERENCES users(user_id)
);

