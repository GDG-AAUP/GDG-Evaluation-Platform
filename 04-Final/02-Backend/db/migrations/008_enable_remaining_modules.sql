-- Storage for Policies, System Log, member scorecards and monthly awards.
-- Only adds tables and relaxes one constraint; no existing data is changed. Re-running is safe.
BEGIN;

SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '60s';

CREATE TABLE IF NOT EXISTS system_policies (
  policy_key VARCHAR(60) PRIMARY KEY,
  policy_value JSONB NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_by_user_id INT NULL REFERENCES users(user_id)
);

-- The schema allows one team and one manager per team, so those options start and stay off.
INSERT INTO system_policies (policy_key, policy_value) VALUES
  ('managerCanEditOrMoveMembers', 'false'),
  ('membersInMultipleTeams', 'false'),
  ('globalLeaderboardEnabled', 'true'),
  ('maxPointsPerOperation', '50'),
  ('multipleManagersPerTeam', 'false')
ON CONFLICT (policy_key) DO NOTHING;

CREATE TABLE IF NOT EXISTS system_logs (
  log_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  level VARCHAR(10) NOT NULL CHECK (level IN ('error', 'warning', 'info')),
  message TEXT NOT NULL,
  source VARCHAR(100) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_system_logs_date ON system_logs (created_at DESC);

-- Monthly 15-item scorecards. Every save is a new revision; the highest revision is effective.
-- performance_evaluations stays dedicated to the four-criterion manager evaluations.
CREATE TABLE IF NOT EXISTS performance_scorecards (
  scorecard_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  target_user_id INT NOT NULL REFERENCES users(user_id),
  year SMALLINT NOT NULL CHECK (year >= 2000),
  month SMALLINT NOT NULL CHECK (month BETWEEN 1 AND 12),
  revision INT NOT NULL CHECK (revision >= 1),
  scores JSONB NOT NULL,
  total_score SMALLINT NOT NULL CHECK (total_score BETWEEN 0 AND 100),
  core_score SMALLINT NOT NULL CHECK (core_score BETWEEN 0 AND 50),
  performed_by_user_id INT NOT NULL REFERENCES users(user_id),
  reason TEXT NOT NULL CHECK (CHAR_LENGTH(TRIM(reason)) > 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_scorecard_revision UNIQUE (target_user_id, year, month, revision),
  CONSTRAINT chk_scorecard_not_self CHECK (target_user_id <> performed_by_user_id)
);

CREATE TABLE IF NOT EXISTS monthly_awards (
  campus_id INT NOT NULL REFERENCES campuses(campus_id),
  year SMALLINT NOT NULL CHECK (year >= 2000),
  month SMALLINT NOT NULL CHECK (month BETWEEN 1 AND 12),
  user_id INT NOT NULL REFERENCES users(user_id),
  team_id INT NOT NULL REFERENCES teams(team_id),
  total_points INT NOT NULL,
  selected_by_user_id INT NOT NULL REFERENCES users(user_id),
  selected_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (campus_id, year, month)
);

-- Activities are stored in the points ledger. Their names can reach 160 characters, and a
-- documented activity may be worth 0 points, which manual point entries still cannot be.
ALTER TABLE point_entries ALTER COLUMN activity_name TYPE VARCHAR(160);
ALTER TABLE point_entries DROP CONSTRAINT IF EXISTS chk_points_range;
ALTER TABLE point_entries ADD CONSTRAINT chk_points_range
  CHECK (points BETWEEN -100 AND 100 AND (points <> 0 OR activity_description IS NOT NULL));

COMMIT;
