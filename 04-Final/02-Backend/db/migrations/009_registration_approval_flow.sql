-- 009: self-registration with organizer approval.
-- People who sign up at Clerk are recorded here, NOT in users, until an organizer approves them.
-- Keeping them out of users means a pending person can never satisfy any existing access rule,
-- ranking query or constraint (users.role stays NOT NULL). Approval creates the users row.
-- Safe to run more than once.

CREATE TABLE IF NOT EXISTS registration_requests (
  request_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  clerk_user_id       VARCHAR(255) NOT NULL UNIQUE,
  email               VARCHAR(255) NOT NULL,
  full_name           VARCHAR(100) NOT NULL,
  registration_status VARCHAR(20)  NOT NULL DEFAULT 'pending',
  rejection_reason    TEXT NULL,
  requested_at        TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  decided_at          TIMESTAMPTZ  NULL,
  decided_by_user_id  INT NULL REFERENCES users(user_id),
  approved_user_id    INT NULL REFERENCES users(user_id),
  -- Outcome of the decision email: sent, failed, or skipped (SMTP not configured).
  notification_status VARCHAR(20)  NULL,
  CONSTRAINT chk_registration_status CHECK (registration_status IN ('pending', 'approved', 'rejected')),
  CONSTRAINT chk_registration_name CHECK (CHAR_LENGTH(TRIM(full_name)) > 0),
  CONSTRAINT chk_registration_reason CHECK (rejection_reason IS NULL OR CHAR_LENGTH(rejection_reason) <= 1000),
  CONSTRAINT chk_registration_decision CHECK (
    (registration_status = 'pending' AND decided_at IS NULL AND decided_by_user_id IS NULL AND approved_user_id IS NULL)
    OR (registration_status = 'approved' AND decided_at IS NOT NULL AND approved_user_id IS NOT NULL)
    OR (registration_status = 'rejected' AND decided_at IS NOT NULL AND approved_user_id IS NULL)),
  CONSTRAINT chk_registration_notification CHECK (notification_status IS NULL OR notification_status IN ('sent', 'failed', 'skipped'))
);

-- One open request per email address.
CREATE UNIQUE INDEX IF NOT EXISTS uq_registration_pending_email
  ON registration_requests (LOWER(email)) WHERE registration_status = 'pending';

-- The organizer badge and list read pending requests oldest first.
CREATE INDEX IF NOT EXISTS ix_registration_status_requested
  ON registration_requests (registration_status, requested_at);
